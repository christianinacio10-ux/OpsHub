  function normalizar(codigo) {
    var s = String(codigo == null ? '' : codigo).toLowerCase().replace(/_/g, '-').trim();
    if (s.indexOf('en') === 0) return 'en';
    if (s.indexOf('es') === 0) return 'es';
    if (s.indexOf('pt') === 0) return 'pt';
    return 'pt';
  }

  function interpolar(texto, vars) {
    if (!vars) return texto;
    return String(texto).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : '';
    });
  }

  function t(idioma, chave, vars) {
    idioma = normalizar(idioma);
    var dict = TEXTOS[idioma] || TEXTOS.pt;
    var texto = (dict && dict[chave]) || TEXTOS.pt[chave] || chave;
    return interpolar(texto, vars);
  }

  function localeDe(idioma) {
    idioma = normalizar(idioma);
    if (idioma === 'en') return 'en';
    if (idioma === 'es') return 'es';
    return 'pt-BR';
  }

  function htmlLang(idioma) {
    return localeDe(idioma);
  }

  function chaveStatus(v) {
    var s = String(v == null ? '' : v).toLowerCase().replace(/\u00a0/g, ' ');
    try { s = s.normalize('NFD').replace(/[\u0300-\u036f]/g, ''); } catch (e) {}
    s = s.replace(/[^a-z0-9]+/g, ' ').trim();
    if (!s) return '';
    var partes = s.split(' ');
    var i;
    var w;
    for (i = 0; i < partes.length; i++) {
      w = partes[i];
      if (!w) continue;
      if (w.indexOf('cancelad') === 0 || w === 'cancelled' || w === 'canceled' || w === 'cancel') return 'cancelado';
      if (w.indexOf('concluid') === 0 || w === 'done' || w === 'closed' || w === 'complete' || w.indexOf('complet') === 0) return 'concluido';
      if (w === 'atrasado' || w === 'overdue' || w === 'late' || w === 'retrasado' || w === 'vencido') return 'atrasado';
      if (w === 'andamento' || w === 'progress' || w === 'curso') return 'andamento';
    }
    if (s === 'aberto' || s === 'open' || s === 'pending' || s === 'pendiente' || s === 'abierto') return 'aberto';
    if (s === 'em andamento' || s === 'in progress' || s === 'en curso' || s === 'en progreso') return 'andamento';
    return '';
  }

  function rotuloStatus(idioma, status) {
    var k = chaveStatus(status);
    if (k) return t(idioma, 'status_' + k);
    return status == null ? '' : String(status);
  }

  function atual() {
    try {
      if (typeof PropertiesService !== 'undefined') {
        return normalizar(PropertiesService.getScriptProperties().getProperty(CHAVE));
      }
    } catch (e) {}
    return 'pt';
  }

  function salvar(codigo) {
    var idioma = normalizar(codigo);
    try {
      if (typeof PropertiesService !== 'undefined') {
        PropertiesService.getScriptProperties().setProperty(CHAVE, idioma);
      }
    } catch (e) {}
    return idioma;
  }

  function detectarNavegador() {
    try {
      var nav = (typeof navigator !== 'undefined' && (navigator.language || navigator.userLanguage)) || '';
      return normalizar(nav);
    } catch (e) {
      return 'pt';
    }
  }

  return {
    CHAVE: CHAVE,
    IDIOMAS: IDIOMAS,
    TEXTOS: TEXTOS,
    normalizar: normalizar,
    t: t,
    locale: localeDe,
    htmlLang: htmlLang,
    chaveStatus: chaveStatus,
    rotuloStatus: rotuloStatus,
    atual: atual,
    salvar: salvar,
    detectarNavegador: detectarNavegador,
  };
